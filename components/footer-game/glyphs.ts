export function buildWordGrid(word: string = WORD): number[][] {
  const glyphs = word.split("").map((ch) => {
    const g = GLYPHS[ch];
    if (!g) throw new Error(`No glyph for '${ch}'`);
    return g;
  });
  const rows: number[][] = [];
  for (let y = 0; y < GLYPH_ROWS; y++) {
    const row: number[] = [];
    glyphs.forEach((g, gi) => {
      for (const cell of g[y]) row.push(cell === "#" ? 1 : 0);
      if (gi < glyphs.length - 1) row.push(0); // 1-col gap between letters
    });
    rows.push(row);
  }
  return rows;
}
